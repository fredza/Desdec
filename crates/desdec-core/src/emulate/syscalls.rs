/// macOS's x86-64 BSD class, a curated subset. macOS tags each class in the
/// high bits of the number; the caller masks them off before looking up here,
/// so this matches the plain BSD ordinal. Apple ships no stable published
/// table, so only long-standing calls are named.
pub(crate) const fn macos_x86_64(number: u64) -> Option<&'static str> {
    match number {
        1 => Some("exit"),
        3 => Some("read"),
        4 => Some("write"),
        5 => Some("open"),
        6 => Some("close"),
        20 => Some("getpid"),
        73 => Some("munmap"),
        74 => Some("mprotect"),
        197 => Some("mmap"),
        240 => Some("nanosleep"),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_same_number_names_a_different_call_on_each_abi() {
        // 221: a concrete case where sharing one table would have lied.
        assert_eq!(linux_x86_64(221), Some("fadvise64"));
        assert_eq!(linux_arm64(221), Some("execve"));
    }

    #[test]
    fn the_common_calls_land_on_the_right_numbers() {
        assert_eq!(linux_x86_64(0), Some("read"));
        assert_eq!(linux_x86_64(1), Some("write"));
        assert_eq!(linux_x86_64(59), Some("execve"));
        assert_eq!(linux_x86_64(231), Some("exit_group"));

        assert_eq!(linux_arm64(63), Some("read"));
        assert_eq!(linux_arm64(64), Some("write"));
        assert_eq!(linux_arm64(93), Some("exit"));
        assert_eq!(linux_arm64(94), Some("exit_group"));
        assert_eq!(linux_arm64(221), Some("execve"));
        assert_eq!(linux_arm64(222), Some("mmap"));
    }

    #[test]
    fn an_unknown_number_is_left_unnamed_rather_than_guessed() {
        assert_eq!(linux_x86_64(0xffff), None);
        assert_eq!(linux_arm64(0xffff), None);
        assert_eq!(linux_x86(0xffff), None);
    }
}
